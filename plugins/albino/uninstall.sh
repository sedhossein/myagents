#!/usr/bin/env bash
# Removes the albino plugin. Run by the root uninstall.sh. Each step undoes one
# step of install.sh and reports "Already removed." when there is nothing to undo.
set -euo pipefail
# shellcheck source=../../scripts/install-lib.sh
source "$MYAGENTS_DIR/scripts/install-lib.sh"

PLUGIN_NAME="albino"
PLUGIN_ID="${PLUGIN_NAME}@${MYAGENTS_MARKETPLACE}"
PLUGIN_SRC="$MYAGENTS_DIR/plugins/$PLUGIN_NAME"

CLAUDE_PLUGINS_DIR="$HOME/.claude/plugins"
CLAUDE_RULES_DIR="$HOME/.claude/rules"
CURSOR_PLUGIN_LINK="$HOME/.cursor/plugins/local/$PLUGIN_NAME"

COPILOT_HOME="${COPILOT_HOME:-$HOME/.copilot}"

CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
CODEX_PROMPTS_DIR="$CODEX_HOME/prompts"
CODEX_AGENTS_DIR="$CODEX_HOME/agents"
CODEX_SKILLS_DIR="$CODEX_HOME/skills"
CODEX_AGENTS_MD="$CODEX_HOME/AGENTS.md"
# Marks the command skills that installers before the move to skills generated.
CODEX_COMMAND_SKILL_MARKER="<!-- Generated by scripts/gen-codex-command-skills.sh."

need python3

# Claude Code: drop every entry install.sh wrote, plus a statusLine that points
# at the plugin's statusline script (set by the statusline skill), since it
# stops working once ~/.myagents is gone. Prints whether anything changed.
# Then remove the albino rules from ~/.claude/rules/.
if has_claude_code; then
  if quietly python3 - \
      "$PLUGIN_SRC" "$MYAGENTS_MARKETPLACE" "$PLUGIN_ID" \
      "$CLAUDE_PLUGINS_DIR/known_marketplaces.json" \
      "$CLAUDE_PLUGINS_DIR/installed_plugins.json" \
      "$HOME/.claude/settings.json" \
      <<'PY'
import json, os, sys

plugin_src, mkt_name, plugin_id, known_path, installed_path, settings_path = sys.argv[1:7]
changed = False

def load(path):
    try:
        with open(path) as f:
            return json.load(f)
    except FileNotFoundError:
        return None

def save(path, data):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    os.replace(tmp, path)

def drop(container, key):
    global changed
    if isinstance(container, dict) and key in container:
        del container[key]
        changed = True
        return True
    return False

def drop_from(parent, section, key):
    # Removes the section too when this leaves it empty.
    removed = drop(parent.get(section), key)
    if removed and parent[section] == {}:
        del parent[section]
    return removed

known = load(known_path)
if drop(known, mkt_name):
    save(known_path, known)

installed = load(installed_path)
if installed and drop(installed.get("plugins"), plugin_id):
    save(installed_path, installed)

settings = load(settings_path)
if settings is not None:
    touched = drop_from(settings, "enabledPlugins", plugin_id)
    touched = drop_from(settings, "extraKnownMarketplaces", mkt_name) or touched
    command = (settings.get("statusLine") or {}).get("command", "")
    if isinstance(command, str) and command.startswith(plugin_src + "/"):
        touched = drop(settings, "statusLine") or touched
    if touched:
        save(settings_path, settings)

print("removed" if changed else "absent")
PY
  then
    settings_result="$quiet_output"
    rm -rf "$CLAUDE_PLUGINS_DIR/data/$PLUGIN_NAME-$MYAGENTS_MARKETPLACE"
    if ! quietly "$PLUGIN_SRC/scripts/sync-rules.sh" uninstall claude "$CLAUDE_RULES_DIR"; then
      fail "Claude Code" "Could not remove the albino rules from ~/.claude/rules/."
    elif [ "$settings_result" = "removed" ] || [ "$quiet_output" = "changed" ]; then
      ok "Claude Code" "Removed. Restart open sessions to unload it."
    else
      ok "Claude Code" "Already removed."
    fi
  else
    fail "Claude Code" "Could not update the settings in ~/.claude/. Check that the JSON files there are valid."
  fi
fi

if has_cursor; then
  albino_skills=()
  for dir in "$PLUGIN_SRC"/skills/*/; do albino_skills+=("$(basename "$dir")"); done
  albino_agents=()
  for file in "$PLUGIN_SRC"/agents/*.md; do albino_agents+=("$(basename "$file" .md)"); done
  copies_left=false
  for name in "${albino_skills[@]}"; do [ -f "$HOME/.cursor/skills/$name/.myagents" ] && copies_left=true; done
  remove_copied_skills "$HOME/.cursor/skills" "${albino_skills[@]}"
  remove_copied_agents "$HOME/.cursor/agents" "${albino_agents[@]}"
  if [ -L "$CURSOR_PLUGIN_LINK" ] || [ "$copies_left" = true ]; then
    rm -f "$CURSOR_PLUGIN_LINK"
    ok "Cursor" "Removed. Run 'Developer: Reload Window' to unload it."
  else
    ok "Cursor" "Already removed."
  fi
fi

if has_opencode; then
  oc_names=()
  for dir in "$PLUGIN_SRC"/skills/*/; do oc_names+=("$(basename "$dir")"); done
  oc_left=false
  for name in "${oc_names[@]}"; do [ -L "$(opencode_dir)/skills/$name" ] && oc_left=true; done
  for file in "$PLUGIN_SRC"/agents/*.md; do
    grep -qF "<!-- managed by myagents -->" "$(opencode_dir)/agents/$(basename "$file")" 2>/dev/null && oc_left=true
  done
  if quietly unlink_skills "$(opencode_dir)/skills" "${oc_names[@]}" \
    && quietly "$PLUGIN_SRC/scripts/gen-opencode-agents.sh" uninstall "$(opencode_dir)/agents" \
    && quietly "$PLUGIN_SRC/scripts/sync-rules.sh" uninstall opencode "$(opencode_dir)/AGENTS.md"; then
    [ "$quiet_output" = "changed" ] && oc_left=true
    if [ "$oc_left" = true ]; then
      ok "OpenCode" "Removed. Start a new session to unload it."
    else
      ok "OpenCode" "Already removed."
    fi
  else
    fail "OpenCode" "Could not remove the albino files from $(opencode_dir)."
  fi
fi

# Codex: remove the plugin and marketplace, then the agents the generator wrote,
# the albino block in AGENTS.md, and the command skills earlier installers
# generated. Their markers keep hand-written files and text untouched.
if has_codex; then
  removed=false
  codex_failed=false
  if codex_has_marketplace "$MYAGENTS_MARKETPLACE"; then
    if quietly codex plugin remove "$PLUGIN_ID" && quietly codex plugin marketplace remove "$MYAGENTS_MARKETPLACE"; then
      removed=true
    else
      fail "Codex" "Could not remove $PLUGIN_NAME."
      codex_failed=true
    fi
  fi
  for skill in "$CODEX_SKILLS_DIR"/albino-command-*/; do
    if grep -qF "$CODEX_COMMAND_SKILL_MARKER" "$skill/SKILL.md" 2>/dev/null; then
      rm -rf "$skill"
      removed=true
    fi
  done
  for agent in "$CODEX_AGENTS_DIR"/*.toml; do
    if [ -f "$agent" ] && head -n 1 "$agent" | grep -qF "# Generated by scripts/gen-codex-agents.sh."; then
      rm -f "$agent"
      removed=true
    fi
  done
  for link in "$CODEX_PROMPTS_DIR"/*.md; do
    [ -L "$link" ] || continue
    case "$(readlink "$link")" in "$PLUGIN_SRC"/commands/*) rm -f "$link" ;; esac
  done
  if ! quietly "$PLUGIN_SRC/scripts/sync-rules.sh" uninstall codex "$CODEX_AGENTS_MD"; then
    fail "Codex" "Could not remove the albino rules from $CODEX_AGENTS_MD."
    codex_failed=true
  elif [ "$quiet_output" = "changed" ]; then
    removed=true
  fi
  if [ "$codex_failed" = true ]; then
    :
  elif [ "$removed" = true ]; then
    ok "Codex" "Removed. Restart Codex to unload it."
  else
    ok "Codex" "Already removed."
  fi
fi

# Copilot: remove the plugin, the skill links, and the albino blocks from the instructions files.
has_copilot_cli && copilot_marketplace_plugin_remove "$MYAGENTS_MARKETPLACE" "$PLUGIN_NAME"
if has_copilot; then
  copilot_changed=false
  copilot_failed=false
  albino_skills=()
  for dir in "$PLUGIN_SRC"/skills/*/; do albino_skills+=("$(basename "$dir")"); done
  for name in "${albino_skills[@]}"; do
    [ -L "$(copilot_skills_dir)/$name" ] && copilot_changed=true
  done
  unlink_skills "$(copilot_skills_dir)" "${albino_skills[@]}"
  for file in "$COPILOT_HOME/copilot-instructions.md" "$(copilot_jetbrains_dir)/global-copilot-instructions.md"; do
    if ! quietly "$PLUGIN_SRC/scripts/sync-rules.sh" uninstall copilot "$file"; then
      fail "Copilot" "Could not remove the albino rules from $file."
      copilot_failed=true
    elif [ "$quiet_output" = "changed" ]; then
      copilot_changed=true
    fi
  done
  if [ "$copilot_failed" = true ]; then
    :
  elif [ "$copilot_changed" = true ]; then
    ok "Copilot" "Removed. Start a new Copilot chat to unload it."
  else
    ok "Copilot" "Already removed."
  fi
fi

finish
